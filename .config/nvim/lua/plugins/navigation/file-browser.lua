-- lua/plugins/navigation/file-browser.lua

-- ============================================================================
-- Configuration
-- ============================================================================

local function create_config()
  return {
    enabled = true,
  }
end

-- ============================================================================
-- Keymaps
-- ============================================================================

vim.keymap.set("n", "-", function()
  Snacks.explorer()
end, {
  desc = "File Explorer",
})

-- ============================================================================
-- Initialization
-- ============================================================================

return create_config()
